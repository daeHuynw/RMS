CREATE TABLE orders (
  id               BIGINT         NOT NULL AUTO_INCREMENT,
  order_number     VARCHAR(30)    NOT NULL,
  user_id          BIGINT         NULL,
  table_session_id BIGINT         NULL,
  created_by       BIGINT         NULL,
  order_type       VARCHAR(30)    NOT NULL DEFAULT 'DINE_IN',
  status           VARCHAR(30)    NOT NULL DEFAULT 'PENDING',
  subtotal         DECIMAL(12,2)  NOT NULL DEFAULT 0,
  tax_amount       DECIMAL(12,2)  NOT NULL DEFAULT 0,
  total_amount     DECIMAL(12,2)  NOT NULL DEFAULT 0,
  customer_note    VARCHAR(500)   NULL,
  cancel_reason    VARCHAR(500)   NULL,
  idempotency_key  VARCHAR(120)   NULL,
  created_at       DATETIME(3)    NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at       DATETIME(3)    NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uk_orders_number (order_number),
  UNIQUE KEY uk_orders_idempotency (idempotency_key),
  KEY idx_orders_user (user_id),
  KEY idx_orders_session (table_session_id),
  KEY idx_orders_status (status),
  CONSTRAINT fk_orders_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE SET NULL,
  CONSTRAINT fk_orders_session FOREIGN KEY (table_session_id) REFERENCES table_sessions (id) ON DELETE SET NULL,
  CONSTRAINT fk_orders_created_by FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE order_items (
  id           BIGINT         NOT NULL AUTO_INCREMENT,
  order_id     BIGINT         NOT NULL,
  menu_item_id BIGINT         NOT NULL,
  item_name    VARCHAR(150)   NOT NULL,
  unit_price   DECIMAL(12,2)  NOT NULL,
  quantity     INT            NOT NULL,
  status       VARCHAR(30)    NOT NULL DEFAULT 'PENDING',
  note         VARCHAR(500)   NULL,
  created_at   DATETIME(3)    NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at   DATETIME(3)    NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  KEY idx_order_items_order (order_id),
  KEY idx_order_items_menu (menu_item_id),
  CONSTRAINT fk_order_items_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE,
  CONSTRAINT fk_order_items_menu FOREIGN KEY (menu_item_id) REFERENCES menu_items (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
